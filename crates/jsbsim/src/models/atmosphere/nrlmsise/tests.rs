fn input(case: &Case) -> Input {
    let [sec, alt, g_lat, g_long, lst, f107a, f107, ap] = case.x;
    Input {
        year: 0,
        doy: case.doy,
        sec,
        alt,
        g_lat,
        g_long,
        lst,
        f107a,
        f107,
        ap,
        ap_a: case.ap_a,
    }
}

fn close(got: f64, want: f64) -> bool {
    (got - want).abs() <= TOLERANCE * want.abs()
}

#[test]
fn matches_the_c_release() {
    for (i, case) in CASES.iter().enumerate() {
        let out = gtd7(&input(case), &Flags { switches: case.sw }).unwrap();
        for (k, (&got, &want)) in out.d.iter().zip(&case.d).enumerate() {
            assert!(close(got, want), "case {i}: d[{k}] = {got:e}, C {want:e}");
        }
        for (k, (&got, &want)) in out.t.iter().zip(&case.t).enumerate() {
            assert!(close(got, want), "case {i}: t[{k}] = {got:e}, C {want:e}");
        }
    }
}

#[test]
fn a_call_does_not_depend_on_the_one_before() {
    // JSBSim evaluates sea level, then the aircraft's altitude, every frame.
    let high = input(&CASES[2]);
    let sea_level = Input { alt: 0.0, ..high };
    let flags = Flags { switches: JSBSIM };
    let alone = gtd7(&sea_level, &flags).unwrap();
    gtd7(&high, &flags).unwrap();
    assert_eq!(gtd7(&sea_level, &flags).unwrap(), alone);
}

#[test]
fn the_ap_history_switch_needs_a_history() {
    let case = &CASES[15];
    let no_history = Input {
        ap_a: None,
        ..input(case)
    };
    let flags = Flags { switches: case.sw };
    assert_eq!(gtd7(&no_history, &flags), Err(Error::MissingApHistory));
}

#[test]
fn default_flags_are_fgmsis_ones() {
    assert_eq!(Flags::default().switches, JSBSIM);
}
