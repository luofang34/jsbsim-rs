//! Inputs derived from upstream ones the way JSBSim's own Python tests
//! derive them: aircraft whose aerodynamic axes are renamed into another
//! axis system and frame, as `tests/TestAeroFuncFrame.py` does, so that a
//! corpus aircraft exercises every frame FGAerodynamics accepts; the mk82
//! with the stall, hysteresis and reference-point elements other corpus
//! aircraft carry ([`aero_limits`]); the tripod of the FCS tests with a
//! system included ([`tripod`]); the tripod of the ground reaction tests
//! ([`ground`]), standing with `<input>` functions ([`input`]), and of the
//! planet tests ([`planet`]); corpus aircraft without their engines, for
//! the fuel tank tests ([`tanks`]); the piston
//! aircraft and scripts of the engine tests ([`piston`]); and the turbine
//! and turboprop ones of the engine and trim tests ([`turbine`]). The
//! derived files live in `oracle/derived` and are regenerated by
//! `oracle derive`; a test checks that they match their upstream source.

