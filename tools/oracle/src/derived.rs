/// One derived variant.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Variant {
    /// Suffix of the derived aircraft name, e.g. `body` for `mk82_body`.
    pub suffix: &'static str,
    /// New names of DRAG, SIDE and LIFT.
    pub forces: [&'static str; 3],
    /// `frame` attribute of every axis, if any.
    pub frame: Option<&'static str>,
    /// Whether the X and Z force functions are negated, as the body frame
    /// needs for its forces to point the same way as drag and lift.
    pub negate_x_z: bool,
}

/// The variants of `TestAeroFuncFrame.py` other than the unchanged
/// aircraft.
pub const VARIANTS: [Variant; 4] = [
    Variant {
        suffix: "body",
        forces: ["X", "Y", "Z"],
        frame: Some("BODY"),
        negate_x_z: true,
    },
    Variant {
        suffix: "axial",
        forces: ["AXIAL", "SIDE", "NORMAL"],
        frame: None,
        negate_x_z: false,
    },
    Variant {
        suffix: "wind",
        forces: ["X", "Y", "Z"],
        frame: Some("WIND"),
        negate_x_z: false,
    },
    Variant {
        suffix: "stability",
        forces: ["X", "Y", "Z"],
        frame: Some("STABILITY"),
        negate_x_z: false,
    },
];

const ORIGINAL: [&str; 3] = ["DRAG", "SIDE", "LIFT"];
const MOMENTS: [&str; 3] = ["ROLL", "PITCH", "YAW"];

fn axis_tag(name: &str, frame: Option<&str>) -> String {
    match frame {
        Some(f) => format!("<axis name=\"{name}\" frame=\"{f}\">"),
        None => format!("<axis name=\"{name}\">"),
    }
}

/// Appends `<value>-1.0</value>` to the last element closing each function
/// of the axis text, as `TestAeroFuncFrame.py` appends it to the product.
fn negate_functions(axis: &str) -> String {
    let mut out = String::with_capacity(axis.len());
    let mut rest = axis;
    while let Some(end) = rest.find("</function>") {
        let (body, tail) = rest.split_at(end);
        match body.rfind("</") {
            Some(close) => {
                let indent_start = body[..close].rfind('\n').map_or(0, |i| i + 1);
                let indent = &body[indent_start..close];
                out.push_str(&body[..indent_start]);
                out.push_str(indent);
                out.push_str("    <value>-1.0</value>\n");
                out.push_str(&body[indent_start..]);
            }
            None => out.push_str(body),
        }
        out.push_str("</function>");
        rest = &tail["</function>".len()..];
    }
    out.push_str(rest);
    out
}

/// The derived aircraft text of `variant` from the upstream `text` of
/// aircraft `name`; `source` names the upstream file in the header.
pub fn derive(
    text: &str,
    name: &str,
    source: &str,
    variant: &Variant,
) -> Result<String, OracleError> {
    let fail = |message: &str| OracleError::Provenance(format!("{source}: {message}"));
    let header_at = text
        .find("<fdm_config")
        .ok_or_else(|| fail("no <fdm_config>"))?;
    let derived_name = format!("{name}_{}", variant.suffix);
    let mut out = String::with_capacity(text.len() + 512);
    out.push_str(&text[..header_at]);
    out.push_str(&format!(
        "<!--\n  SPDX-License-Identifier: LGPL-2.1-or-later\n  {derived_name}: {source} with its aerodynamic axes renamed\n  {} -> {}{}{},\n  as JSBSim's tests/TestAeroFuncFrame.py derives it. Regenerate with\n  `oracle derive`.\n-->\n",
        ORIGINAL.join("/"),
        variant.forces.join("/"),
        variant.frame.map_or(String::new(), |f| format!(" in the {f} frame")),
        if variant.negate_x_z { ", X and Z negated" } else { "" },
    ));
    let mut rest = &text[header_at..];
    while let Some(start) = rest.find("<axis name=\"") {
        out.push_str(&rest[..start]);
        let after = &rest[start..];
        let tag_end = after.find('>').ok_or_else(|| fail("unterminated <axis>"))? + 1;
        let close = after
            .find("</axis>")
            .ok_or_else(|| fail("unterminated <axis>"))?;
        let tag = &after[..tag_end];
        let body = &after[tag_end..close];
        let old = tag
            .trim_start_matches("<axis name=\"")
            .split('"')
            .next()
            .unwrap_or_default();
        let (new, negate) = if let Some(i) = ORIGINAL.iter().position(|a| *a == old) {
            let new = variant.forces.get(i).copied().unwrap_or(old);
            (new, variant.negate_x_z && (new == "X" || new == "Z"))
        } else if MOMENTS.contains(&old) {
            (old, false)
        } else {
            return Err(fail(&format!("unexpected axis {old}")));
        };
        out.push_str(&axis_tag(new, variant.frame));
        if negate {
            out.push_str(&negate_functions(body));
        } else {
            out.push_str(body);
        }
        out.push_str("</axis>");
        rest = &after[close + "</axis>".len()..];
    }
    out.push_str(rest);
    Ok(out)
}

/// The mk82 [`VARIANTS`] with their `reset00` and script, from the
/// upstream mk82 texts.
fn variant_files(
    aircraft: &str,
    reset: &str,
    script: &str,
) -> Result<Vec<(String, String)>, OracleError> {
    let mut files = Vec::new();
    for v in &VARIANTS {
        let name = format!("mk82_{}", v.suffix);
        files.push((
            format!("aircraft/{name}/{name}.xml"),
            derive(aircraft, "mk82", "aircraft/mk82/mk82.xml", v)?,
        ));
        files.push((format!("aircraft/{name}/reset00.xml"), reset.to_owned()));
        files.push((
            format!("scripts/{name}_script.xml"),
            script.replacen("aircraft=\"mk82\"", &format!("aircraft=\"{name}\""), 1),
        ));
    }
    Ok(files)
}

/// Paths of the derived aircraft and its copied files under
/// `oracle/derived`, with their expected contents.
pub fn expected_blocking(repo_root: &Path) -> Result<Vec<(String, String)>, OracleError> {
    let inputs = repo_root.join("oracle").join("inputs");
    let read = |rel: &str| {
        let path = inputs.join(rel);
        std::fs::read_to_string(&path).map_err(|e| OracleError::io("reading", &path, e))
    };
    let aircraft = read("aircraft/mk82/mk82.xml")?;
    let reset = read("aircraft/mk82/reset00.xml")?;
    let script = read("scripts/mk82_script.xml")?;
    let mut files = variant_files(&aircraft, &reset, &script)?;
    files.extend(aero_limits::files(&aircraft, &reset)?);
    let tripod_text = read("tests/tripod.xml")?;
    files.extend(ground::files(&tripod_text)?);
    files.extend(input::files(&tripod_text)?);
    files.extend(planet::files(&read)?);
    for system in tripod::SYSTEMS {
        let suffix = system.suffix;
        files.push((
            format!("aircraft/tripod_{suffix}/tripod_{suffix}.xml"),
            tripod::derive(&tripod_text, suffix, system.file)?,
        ));
    }
    let function = read("tests/function.xml")?;
    files.push((
        "systems/function_bad_table.xml".to_owned(),
        systems::bad_table(&function)?,
    ));
    let ball = read("aircraft/ball/ball.xml")?;
    let name = accelerometers::AIRCRAFT;
    files.push((
        format!("aircraft/{name}/{name}.xml"),
        accelerometers::aircraft(&ball)?,
    ));
    for reset in ["reset00.xml", "reset00_v2.xml"] {
        files.push((
            format!("aircraft/{name}/{reset}"),
            read(&format!("aircraft/ball/{reset}"))?,
        ));
    }
    files.push((
        "systems/accelerometers.xml".to_owned(),
        read("systems/accelerometers.xml")?,
    ));
    files.push((
        "scripts/ball_orbit_accelerometers.xml".to_owned(),
        accelerometers::orbit_script(&read("scripts/ball_orbit.xml")?)?,
    ));
    files.push((
        "scripts/ball_spin_accelerometers.xml".to_owned(),
        accelerometers::spin_script(),
    ));
    let gnc = read("systems/GNCUtilities.xml")?;
    files.push((
        "systems/gnc_waypoint.xml".to_owned(),
        systems::gnc_waypoint(&gnc)?,
    ));
    files.push((
        "systems/actuator_c172x.xml".to_owned(),
        actuator::system(&read("aircraft/c172x/c172x.xml")?)?,
    ));
    for system in &kinematic::SYSTEMS {
        files.push((
            format!("systems/{}", system.file),
            kinematic::derive(&read(system.source)?, system)?,
        ));
    }
    files.extend(tank_files(&read)?);
    files.extend(piston::files(&read)?);
    files.extend(piston_scenarios::files(&read)?);
    turbine::files(&read, &mut files)?;
    Ok(files)
}

/// The [`tanks`] aircraft, with copies of the files they include from
/// their aircraft directories.
fn tank_files(
    read: &dyn Fn(&str) -> Result<String, OracleError>,
) -> Result<Vec<(String, String)>, OracleError> {
    let mut files = Vec::new();
    for t in tanks::AIRCRAFT {
        let (name, source) = (t.name, t.source);
        let text = read(&format!("aircraft/{source}/{source}.xml"))?;
        files.push((
            format!("aircraft/{name}/{name}.xml"),
            tanks::derive(&text, t)?,
        ));
        for include in tanks::includes(source) {
            files.push((
                format!("aircraft/{name}/{include}"),
                read(&format!("aircraft/{source}/{include}"))?,
            ));
        }
    }
    Ok(files)
}

/// Writes every derived file into `oracle/derived`.
pub fn write_blocking(repo_root: &Path) -> Result<(), OracleError> {
    let dir = repo_root.join("oracle").join("derived");
    for (rel, text) in expected_blocking(repo_root)? {
        let path = dir.join(&rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| OracleError::io("creating", parent, e))?;
        }
        std::fs::write(&path, text).map_err(|e| OracleError::io("writing", &path, e))?;
    }
    Ok(())
}
